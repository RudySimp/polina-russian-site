import fs from "node:fs/promises";
import path from "node:path";
async function writeDifferent(filename, value) {
  try {
    if ((await fs.readFile(filename, "utf8")) === value) return;
  } catch {}
  await fs.writeFile(filename, value);
}
export async function buildOgeCourse() {
  const root = path.resolve("apps/showcase/src/content");
  const existing = JSON.parse(
    await fs.readFile("content/oge-course.json", "utf8"),
  ).modules;
  const original = JSON.parse(
    await fs.readFile("content/oge-theory-modules.json", "utf8"),
  ).modules;
  const all = [...existing, ...original];
  const ids = new Set(all.map((m) => m.id));
  if (ids.size !== all.length) throw Error("Duplicate OGE course module");
  const index = [],
    loaders = [],
    search = [];
  await fs.mkdir(path.join(root, "course-modules"), { recursive: true });
  for (const m of all) {
    if (
      !/^[a-z0-9-]+$/.test(m.id) ||
      !m.title ||
      !m.outcome ||
      !m.prerequisiteIds.every((id) => ids.has(id) && id !== m.id)
    )
      throw Error("Invalid OGE module " + m.id);
    const chapter = m.kind === "chapter-sections";
    const lesson = chapter
      ? JSON.parse(
          await fs.readFile(
            path.join(root, "lessons", m.topicId + ".json"),
            "utf8",
          ),
        )
      : m.lesson;
    if (
      !lesson ||
      !lesson.sections.length ||
      lesson.sections.some((s) => !s.blocks.length)
    )
      throw Error("Incomplete OGE module " + m.id);
    const sectionIds = chapter
      ? m.sectionIds
      : lesson.sections.map((s) => s.id);
    if (
      !sectionIds.length ||
      sectionIds.some((id) => !lesson.sections.some((s) => s.id === id))
    )
      throw Error("Invalid section reference " + m.id);
    const metadata = Object.fromEntries(
      Object.entries(m).filter(
        ([key]) => !["lesson", "checkpoint", "review"].includes(key),
      ),
    );
    const checkpoint = m.checkpoint;
    index.push({
      ...metadata,
      kind: chapter ? "chapter-sections" : "original",
      sectionIds,
      sourceLessonId: lesson.id,
      sourceLessonRevision: lesson.revision,
      review: "checked-demo",
      teacherApproval: "pending",
    });
    if (!chapter)
      for (const section of lesson.sections) {
        const displayed = [];
        const excluded =
          /^(?:id|topicId|type|kind|expected|answer|revision|provenance|sourceId|sourceSha256|method|teacherApproval|reviewedAt|importedAt)$/;
        function collect(value) {
          if (typeof value === "string") displayed.push(value);
          else if (Array.isArray(value)) value.forEach(collect);
          else if (value && typeof value === "object")
            for (const [key, child] of Object.entries(value))
              if (!excluded.test(key)) collect(child);
        }
        collect(section.blocks);
        search.push({
          topicId: m.topicId,
          moduleId: m.id,
          sectionId: section.id,
          title: section.title,
          text: displayed.join(" "),
          route: "/oge/theory/modules/" + m.id + "/#" + section.id,
        });
      }
    const payload = chapter ? { checkpoint } : { lesson };
    await writeDifferent(
      path.join(root, "course-modules", m.id + ".json"),
      JSON.stringify(payload) + "\n",
    );
    loaders.push(
      "  '" +
        m.id +
        "': () => import('./course-modules/" +
        m.id +
        ".json').then(m => m.default as CoursePayload)",
    );
  }
  await writeDifferent(
    path.join(root, "course-search.json"),
    JSON.stringify(search) + "\n",
  );
  await writeDifferent(
    path.join(root, "course-index.json"),
    JSON.stringify(index) + "\n",
  );
  await writeDifferent(
    path.join(root, "course-loaders.ts"),
    "// Generated by scripts/lib/build-oge-course.mjs.\nimport type { CoursePayload } from './course-model';\nexport const courseModuleLoaders: Record<string, () => Promise<CoursePayload>> = {\n" +
      loaders.join(",\n") +
      "\n};\n",
  );
  console.log("OGE course: " + index.length + " completed module routes.");
}
