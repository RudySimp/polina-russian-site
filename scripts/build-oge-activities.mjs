const situation = (id, title, text, fields, explanation, details, tokens) => ({
  id,
  title,
  instruction:
    "Выполните действие и проверьте. После разбора можно исправить ответ.",
  text,
  fields,
  explanation,
  details,
  ...(tokens ? { tokens } : {}),
});
