import fs from "node:fs/promises";
const additions = [];
const field = (id, label, expected, explanation, options) => ({
  id,
  label,
  expected: Array.isArray(expected) ? expected : [expected],
  explanation,
  ...(options ? { options } : {}),
});
function add(kind, id, title, text, fields, explanation, tokens) {
  additions.push({
    activityId: kind,
    situation: {
      id: `audit-${id}`,
      revision: 1,
      title,
      instruction:
        "Выполните действие самостоятельно. После ошибки изучите причину и проверьте новый аналогичный случай." +
        (kind === "correction" && id === "imperative"
          ? " Сохраните несовершенный вид глагола; запишите одну нормативную форму."
          : ""),
      text,
      fields,
      explanation,
      details: fields.map((field) => `${field.label}: ${field.explanation}`),
      skillIds: [kind],
      hint: "Найдите основание правила и отделите его от отвлекающих деталей. Проверьте каждый шаг, прежде чем переходить дальше.",
      ...(tokens ? { tokens } : {}),
    },
  });
}
