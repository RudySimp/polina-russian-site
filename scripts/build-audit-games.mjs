const path = "apps/showcase/src/oge/activities.json";
const activities = JSON.parse(await fs.readFile(path, "utf8"));
const subskills = JSON.parse(
  await fs.readFile("apps/showcase/src/content/subskills.json", "utf8"),
);
for (const activity of activities) {
  activity.situations = activity.situations.filter(
    (item) => !item.id.startsWith("audit-"),
  );
  for (const item of activity.situations) item.revision ??= 1;
  activity.situations.push(
    ...additions
      .filter((item) => item.activityId === activity.id)
      .map((item) => item.situation),
  );
  for (const situation of activity.situations) {
    const searchable = `${situation.title} ${situation.text} ${situation.explanation}`;
    const skills = subskills
      .filter(
        (skill) =>
          skill.topicId === activity.topicId &&
          new RegExp(skill.pattern, "iu").test(searchable),
      )
      .map((skill) => skill.id);
    situation.skillIds = skills.length ? skills : [activity.skillId];
  }
}
await fs.writeFile(path, JSON.stringify(activities, null, 2) + "\n");
